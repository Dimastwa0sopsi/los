import { useState } from 'react';
import { Modal } from './MenuScreens';
import { bindingsFor } from '../game/keys';

type TabId = 'start' | 'foot' | 'car' | 'money' | 'home' | 'world';

const TABS: { id: TabId; name: string; icon: string }[] = [
  { id: 'start', name: 'Начало', icon: '🚀' },
  { id: 'foot', name: 'Пешком', icon: '🚶' },
  { id: 'car', name: 'Машина', icon: '🚗' },
  { id: 'money', name: 'Деньги', icon: '💵' },
  { id: 'home', name: 'Дом', icon: '🏠' },
  { id: 'world', name: 'Мир', icon: '🌍' },
];

/** строка «клавиша — действие» */
function Key({ k, children }: { k: string; children: React.ReactNode }) {
  return <div className="hlp-row"><kbd>{k}</kbd><span>{children}</span></div>;
}

/**
 * «Как играть?» — всё обучение живёт здесь, а не поверх игры.
 * Раньше подсказки вылезали в бою и мешали; теперь экран чистый, а справка — по кнопке.
 */
export function HelpPanel({ close, startTab = 'start', mobile = false }: { close: () => void; startTab?: TabId; mobile?: boolean }) {
  const [tab, setTab] = useState<TabId>(startTab);
  return (
    <Modal title="❓ Как играть" onClose={close} wide>
      <div className="hlp-tabs">
        {TABS.map((t) => (
          <button key={t.id} className={`hlp-tab ${tab === t.id ? 'on' : ''}`} onClick={() => setTab(t.id)}>
            <span>{t.icon}</span>{t.name}
          </button>
        ))}
      </div>
      <div className="hlp-body">
        {tab === 'start' && (
          <>
            <p className="hlp-lead">Лос-Город — песочница: работай, покупай машины и жильё, гоняй, отдыхай. Никто не заставляет идти по сюжету.</p>
            <h6>Первые шаги</h6>
            <Key k="WASD">идти · <b>Shift</b> — бег</Key>
            <Key k="мышь">смотреть по сторонам · <b>колесо</b> — приблизить</Key>
            <Key k="E">действие рядом (войти, купить, сесть) — подсказка появляется внизу</Key>
            <Key k="Tab">телефон: карта, работа, объявления, банк</Key>
            <Key k="T">чат и команды · <b>/help</b> — список команд</Key>
            <Key k="U">музыка и радио — где угодно, хоть пешком</Key>
            <Key k="C">присесть</Key>
            <Key k="Esc">пауза и настройки</Key>
            <Key k="F1">эта справка в любой момент</Key>
            <h6>Если играешь с телефона</h6>
            <p>Слева — джойстик (или кнопки-стрелки, переключается в настройках), справа — газ/тормоз и действия, свайп по правой половине экрана — камера. Кнопка ☰ открывает меню: инвентарь, карта, телефон, настройки.</p>
            <p>Правую панель можно собрать под себя: ⚙️ Настройки → 🎮 Управление → «Кнопки справа на телефоне». Нажмите кнопку — она появится на панели, нажмите ещё раз — уберётся. Лишнее не теряется: в игре оно лежит под «⋯» рядом с панелью, оттуда одной касание ставится обратно. Раскладка — дугой или сеткой 2×2, для пешком и для машины отдельно.</p>
            <p>Раскладка меняется на лету: Настройки → Управление → «Джойстик / Крестовина», там же можно включить режим ПК.</p>
          </>
        )}
        {tab === 'foot' && (
          <>
            <h6>Движение и взаимодействие</h6>
            {bindingsFor('foot').map((b) => <Key key={b.action} k={b.key}>{b.what}</Key>)}
            <Key k="V">вид от первого / третьего лица</Key>
            <h6>Драки и оружие</h6>
            <Key k="ЛКМ">удар или выстрел</Key>
            <Key k="ПКМ">прицеливание / блок</Key>
            <Key k="1…5">выбор оружия из хотбара</Key>
            <p>Ствол в руках у кассира — это ограбление: деньги быстро, но растёт розыск. Полиция видит по звёздам вверху справа.</p>
            <h6>Эмоции</h6>
            <Key k="/">танцы</Key>
            <p>Эмоции и позы — в телефоне: приложение «Эмоции» на главном экране.</p>
          </>
        )}
        {tab === 'car' && (
          <>
            <h6>За рулём</h6>
            <Key k="W S">газ и тормоз (задний ход на S)</Key>
            <Key k="A D">руль</Key>
            {bindingsFor('car').map((b) => <Key key={b.action} k={b.key}>{b.what}</Key>)}
            <Key k="Q + 1…6">передачи в механической коробке</Key>
            <Key k="U">музыка и радио (работает и пешком)</Key>
            <Key k="T">чат</Key>
            <h6>Самокаты и аренда</h6>
            <p>🛴 Стойки аренды стоят в городе, у «Вжух Store» и в каждой деревне. Садись — и катайся, деньги списываются за минуты. Электросамокат не требует прав и бензина.</p>
            <h6>Гонки</h6>
            <p>Уличная гонка — на телефоне в меню «Машина», на ПК кнопка в планшете. Приз только деньгами, никаких ставок на машину.</p>
          </>
        )}
        {tab === 'money' && (
          <>
            <h6>Откуда деньги</h6>
            <p>Смены в магазинах (R у кассы), доставка, дальнобойщики, такси, комбайн на ферме, шахта «Чёрная Жила», скупка урожая, объявления на телефоне, гонки и казино.</p>
            <h6>Банк и сделки</h6>
            <Key k="/pay">перевести деньги игроку</Key>
            <Key k="/give">передать предмет</Key>
            <Key k="/obm">обмен вещами</Key>
            <h6>Правила игры с деньгами</h6>
            <p>Деньги, которые тебе пришли, никто не отбирает: ни сервер, ни модератор. Максимум придёт уведомление.</p>
            <p>Купить можно почти всё: еду и воду в магазинах, одежду, оружие, тюнинг, машины, квартиры и дома. Всё купленное остаётся в сохранении.</p>
          </>
        )}
        {tab === 'home' && (
          <>
            <h6>Жильё</h6>
            <p>Дом или квартира покупается у двери (E) — если она свободна. Своё жильё можно запереть на L, внутри есть кровать, холодильник и компьютер.</p>
            <h6>Бизнес и имущество</h6>
            <p>Гаражи, парковки, ларьки и грядки покупаются и приносят доход. Оранжерея и подвал — для растений, продажа урожая — в магазинах.</p>
            <h6>Транспорт</h6>
            <p>Купленная машина появляется на парковке у дома или в гараже. Угнанную полиция ищет — смотри звёзды розыска.</p>
          </>
        )}
        {tab === 'world' && (
          <>
            <h6>Что есть в городе</h6>
            <p>Мэрия, банк, больница, полиция, пожарная, торговый центр, авторынок, автосалоны, автосервисы и тюнинг, кафе и бары, «Вжух Store» с самокатами, два казино — одно за городом («Жар-Птица»), второе в городе («Золотой Лось»).</p>
            <h6>Деревни</h6>
            <p>Сосновка, Кленовка и Ольховка: сельмаг, администрация, аптека, ферма, стойки самокатов. Дороги — деревенские, зимой и в дождь лучше не гнать.</p>
            <h6>Погода</h6>
            <p>Прогноз приходит в чат от «🌤 Погоды»: ясно, облачно, дождь или снег. На управление погода не влияет — это картинка и настроение.</p>
            <h6>Онлайн</h6>
            <p>Ник входа и пароль — как в обычной игре. Если сервер недоступен, мир продолжит работать офлайн, прогресс сохранится.</p>
            {mobile && <p className="hlp-note">Совет: играй в горизонтальной ориентации — кнопок больше и они не мешают друг другу.</p>}
          </>
        )}
      </div>
      <div className="hlp-foot">
        <button className="lg-btn lg-btn-main" onClick={close}>Понятно</button>
      </div>
    </Modal>
  );
}
