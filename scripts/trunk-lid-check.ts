import { strict as assert } from 'node:assert';
import * as THREE from 'three';
import { VEHICLES } from '../src/game/data';
import { createTrunkLidPrototype } from '../src/game/trunkLid';
import { TRUNK_OPEN_SECONDS } from '../src/game/trunkAnimation';
const sedan = Object.values(VEHICLES).find(v => v.body === 'sedan')!;
const truck = Object.values(VEHICLES).find(v => v.body === 'truck')!;
const moto = Object.values(VEHICLES).find(v => v.body === 'moto')!;
assert.equal(createTrunkLidPrototype(moto, '#fff'), null);
const lid = createTrunkLidPrototype(sedan, '#ff0000')!;
assert.equal(lid.kind, 'hinged');
lid.setElapsed(0); assert.equal(lid.group.rotation.x, 0);
lid.setElapsed(TRUNK_OPEN_SECONDS.hinged); assert(lid.group.rotation.x > 1);
lid.setElapsed(0); assert.equal(lid.group.rotation.x, 0);
const parent = new THREE.Group(); parent.add(lid.group); lid.dispose(); assert.equal(parent.children.length, 0);
const door = createTrunkLidPrototype(truck, '#fff')!;
assert.equal(door.kind, 'rollup');
const mesh = door.group.children[0]; const y = mesh.position.y;
door.setElapsed(TRUNK_OPEN_SECONDS.rollup); assert(mesh.position.y > y);
door.setElapsed(0); assert.equal(mesh.position.y, y); door.dispose();
console.log('✓ отдельный прототип крышки и грузовой двери, открытие/закрытие и отсутствие у мотоцикла');
