import {strict as assert} from 'node:assert';
import {stepCustody,validCustodyState,JAIL_SENTENCE_MS,type CustodyState} from '../src/game/policeCustodyLab';
const free:CustodyState={phase:'free'},id='arrest-request-00000001';
const arrest={type:'arrest' as const,custodyId:id,stationId:42,wanted:3,policePresent:true,stopped:true,now:1000};
assert.equal(stepCustody(free,{...arrest,wanted:2}).ok,false);
assert.equal(stepCustody(free,{...arrest,policePresent:false}).ok,false);
assert.equal(stepCustody(free,{...arrest,stopped:false}).ok,false);
let result=stepCustody(free,arrest);assert(result.ok && result.state.phase==='transport');
let transport:CustodyState=JSON.parse(JSON.stringify(result.state));assert(validCustodyState(transport));
assert(!stepCustody(transport,arrest).ok);
assert(!stepCustody(transport,{type:'release',custodyId:id,now:90000}).ok);
assert(!stepCustody(transport,{type:'arrive',custodyId:id,stationId:43,now:2000}).ok);
assert(!stepCustody(transport,{type:'arrive',custodyId:id,stationId:42,now:999}).ok);
result=stepCustody(transport,{type:'arrive',custodyId:id,stationId:42,now:10000});assert(result.ok && result.state.phase==='jailed');
const jailed:CustodyState=JSON.parse(JSON.stringify(result.state));assert(validCustodyState(jailed));
assert.equal(jailed.releaseAt,10000+JAIL_SENTENCE_MS);
assert(!stepCustody(jailed,{type:'arrive',custodyId:id,stationId:42,now:20000}).ok);
assert(!stepCustody(jailed,{type:'release',custodyId:'another-request-00000001',now:80000}).ok);
assert(!stepCustody(jailed,{type:'release',custodyId:id,now:69999}).ok);
assert(stepCustody(jailed,{type:'release',custodyId:id,now:70000}).ok);
assert(!validCustodyState({...jailed,releaseAt:10001}));assert(!validCustodyState({...transport,startedAt:-1}));
assert(!stepCustody({...jailed,releaseAt:10001},{type:'release',custodyId:id,now:80000}).ok);
console.log('✓ прототип задержания: три звезды, доставка, минута после прибытия, запрет раннего выхода, повтор и перезапуск');
