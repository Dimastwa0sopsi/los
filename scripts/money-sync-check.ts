import './domstub';
import { NetClient } from '../src/game/net';
import { Game } from '../src/game/game';
(globalThis as any).WebSocket = { OPEN: 1 };
const storage = new Map<string, string>();
(globalThis as any).localStorage = { getItem: (k: string) => storage.get(k) ?? null, setItem: (k: string, v: string) => storage.set(k, v) };
const net = new NetClient('tester', 'm', 'ws://test') as any;
const sent: any[] = [];
net.ws = { readyState: 1, send: (s: string) => sent.push(JSON.parse(s)) };
let calls = 0;
net.onLogin = () => calls++;
const assert = (ok: unknown, msg: string) => { if (!ok) throw new Error(msg); console.log('✓ ' + msg); };
net.sendSave(20000);
assert(sent.length === 0, 'баланс не отправляется до входа');
net.handshake = true;
net.handle(JSON.stringify({ type: 'login_success', caps: { accounts: 1 }, accountRevision: 0, player: { id: 1, name: 'tester', money: 500000 } }));
net.sendSave(250000);
assert(sent.length === 1 && sent[0].money === 250000, 'покупка отправляется на сервер');
net.handle(JSON.stringify({ type: 'players_list', players: [{ id: 1, name: 'tester', money: 500000 }] }));
assert(calls === 1, 'устаревший список игроков не меняет баланс');
net.sendSave(250000);
assert(sent.length === 1, 'неизменный баланс не отправляется повторно');
net.authenticated = false; net.lastSaveMoney = NaN;
net.sendSave(240000);
assert(sent.length === 1, 'при разрыве баланс не считается отправленным');
net.handshake = true;
net.handle(JSON.stringify({ type: 'login_success', caps: { accounts: 1 }, accountRevision: 0, player: { id: 1, name: 'tester', money: 250000 } }));
net.sendSave(240000);
assert(sent.length === 2 && sent[1].money === 240000, 'после переподключения изменения отправляются');
const g = Object.create(Game.prototype) as any;
g.state = { money: 19500, look: { gender: 'm' } }; g.onlineInitialMoney = 20000; g.net = net; g.save = () => {}; g.player = { setLook: () => {} }; g.interior = true;
g.applyServerPlayer({ money: 500000 }, true);
assert(g.state.money === 499500, 'операция до входа не теряется');
g.state.money = 249500;
g.applyServerPlayer({ money: 500000 }, false);
assert(g.state.money === 249500, 'переподключение не возвращает старый баланс');
