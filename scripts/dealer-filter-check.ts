import {strict as assert} from 'node:assert';
import {dealerVehicles,dealerCategories,filterDealerVehicles} from '../src/game/dealerFilter';
import {VEHICLES} from '../src/game/data';
const stock=dealerVehicles(), filters={query:'',category:'all' as const,budget:''};
assert(stock.length>0);assert(stock.every(v=>v.forSale==='dealer'));assert(stock.every((v,i)=>i===0||stock[i-1].price<=v.price));
assert.deepEqual(filterDealerVehicles(stock,filters),stock);
assert(filterDealerVehicles(stock,{...filters,query:'  ВИРАЖ  '}).some(v=>v.id==='kolibri'));
assert.deepEqual(filterDealerVehicles(stock,{...filters,query:'KoLiBrI'}).map(v=>v.id),['kolibri']);
assert(dealerCategories(stock).includes('bus'));assert(!dealerCategories(stock).includes('combine'));
assert(filterDealerVehicles(stock,{...filters,category:'moto'}).every(v=>v.body==='moto'));
assert(filterDealerVehicles(stock,{...filters,budget:'10000'}).every(v=>v.price<=10000));
assert(filterDealerVehicles(stock,{...filters,budget:'0'}).every(v=>v.price===0));
assert.equal(filterDealerVehicles(stock,{...filters,budget:'abc'}).length,0);
assert.equal(filterDealerVehicles(stock,{...filters,budget:'999999999999999999999'}).length,0);
assert.deepEqual(filterDealerVehicles(stock,{...filters,query:'вираж gt',category:'hatch',budget:String(VEHICLES.kolibri.price)}).map(v=>v.id),['kolibri']);
assert.equal(filterDealerVehicles(stock,{...filters,query:'вираж gt',category:'hatch',budget:String(VEHICLES.kolibri.price-1)}).length,0);
assert.equal(filterDealerVehicles(stock,{...filters,query:'вираж',category:'bus'}).length,0);
assert(dealerVehicles(true).every(v=>v.forSale==='scooter'));assert(!dealerVehicles(true).some(v=>v.forSale==='dealer'));
console.log('✓ автосалон: поиск по названию, категория, бюджет, комбинации и ассортимент');
