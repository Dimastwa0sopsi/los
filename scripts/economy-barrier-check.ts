import {EconomyBarrier} from '../src/game/economyBarrier';
const assert = (x: unknown, msg: string) => {if (!x) throw Error(msg);};
const barrier = new EconomyBarrier(), id='request-0000000000000001';
const request = {requestId:id,revision:4,action:'bid',payload:{lot:1,amount:1000}};
const state = {money:10000,inventory:{water:2}};
assert(!barrier.begin(request,false,state),'нельзя начать пока сейв не подтверждён');
assert(barrier.begin(request,true,state) && barrier.blocked,'очередь блокируется');
assert(!barrier.begin(request,true,state),'одновременно только одна операция');
request.payload.amount=9999; assert((barrier.retry()?.payload as any).amount===1000,'повтор с неизменным payload');
const receipt = {ok:true,requestId:id,revision:5,state:{money:9000,inventory:{water:2}}};
assert(!barrier.installed(id,receipt.state,5),'нельзя разблокировать без принятия');
assert(!barrier.accept({...receipt,requestId:'request-other'},state).ok,'чужой ответ');
assert(!barrier.accept({...receipt,revision:4},state).ok,'старая ревизия');
const changed = {...state,money:8000}; const conflict = barrier.accept(receipt,changed);
assert(!conflict.ok && conflict.error==='local_changed' && barrier.blocked,'локальные изменения нельзя потерять');
const result = barrier.accept(receipt,state);
assert(result.ok && (result.state as any).money===9000 && result.revision===5,'снимок операции');
assert(!barrier.installed(id,state,5) && barrier.blocked,'до установки разблокировка запрещена');
assert(barrier.installed(id,receipt.state,5) && !barrier.blocked,'установленный результат разблокирует');
assert(barrier.begin({...request,revision:5,requestId:'request-0000000000000002'},true,state),'следующий запрос');
const expired = barrier.accept({ok:false,requestId:'request-0000000000000002',committed:true,error:'receipt_expired'},state);
assert(!expired.ok && expired.error==='committed_recovery_required' && barrier.blocked,'нет повторного списания при истечении истории');
console.log('✓ экспериментальный барьер: очередь, повтор, конфликт, установка, истекший ответ');
