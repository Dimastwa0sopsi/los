'use strict';
const assert = require('node:assert/strict');
const Database = require('better-sqlite3');
const { createAccountStore } = require('../server/account-store.cjs');
(async () => {
  const db = new Database(':memory:'); const store = createAccountStore(db);
  let result = await store.register('Тест', 'длинный пароль 123', 'резервный пароль 456');
  assert(result.ok && result.revision === 0 && result.state === null);
  assert.equal((await store.register('тест', 'другой пароль 123')).error, 'exists');
  assert.equal((await store.login('Тест', 'неверный пароль')).error, 'credentials');
  assert((await store.login('тест', 'длинный пароль 123')).ok);
  assert((await store.login('тест', 'резервный пароль 456')).ok);
  assert(!(await store.login('тест', 'неверный резервный пароль')).ok);
  const state = { money: 12345, health: 54, food: 34, water: 42, vehicles: [{ uid: 'a', type: 'lada' }], properties: ['1120:0'], garages: [22] };
  assert.deepEqual(store.save('Тест', state, 0), { ok: true, revision: 1 });
  assert.equal(store.save('Тест', { money: 0 }, 0).error, 'conflict');
  result = await store.login('Тест', 'длинный пароль 123');
  assert.deepEqual(result.state, state); assert.equal(result.revision, 1);
  const r = store.issueReset('Тест', 1000); assert(r);
  assert(!(await store.resetPassword('Тест', r.code, 'совсем новый пароль', r.expiresAt)));
  assert(await store.resetPassword('Тест', r.code, 'совсем новый пароль', 1001));
  assert(!(await store.resetPassword('Тест', r.code, 'ещё новый пароль', 1002)));
  assert(!(await store.login('Тест', 'длинный пароль 123')).ok);
  assert((await store.login('Тест', 'совсем новый пароль')).ok);
  assert.equal(store.save('Тест', { data: 'x'.repeat(1024 * 1024) }, 1).error, 'too_large');
  const sid = 'stable-request-00000000001', s2 = {money:100, vehicles:[]};
  assert.deepEqual(store.save('Тест', s2, 1, sid), {ok:true,revision:2});
  assert.deepEqual(store.save('Тест', s2, 1, sid), {ok:true,revision:2,replay:true});
  assert.equal(store.save('Тест', {...s2,money:1}, 1, sid).error, 'request_reused');
  assert.equal(store.save('Тест', s2, 2, sid).error, 'request_reused');
  assert.equal((await store.login('Тест','совсем новый пароль')).state.money,100);
  assert(store.save('Тест', {...s2,money:110},2,'stable-request-00000000002').ok);
  assert.equal(store.save('Тест', s2, 1, sid).error,'conflict');
  const legacy = store.prepareLegacy('Старый игрок', 2000); assert(legacy);
  assert(!(await store.login('Старый игрок', 'чужой пароль 123')).ok);
  assert(store.prepareLegacy('Старый игрок', 2001) === null);
  assert(await store.resetPassword('Старый игрок', legacy.code, 'первый пароль 123', 2001));
  assert((await store.login('Старый игрок', 'первый пароль 123')).ok);
  db.close(); console.log('✓ регистрация, авторизация, сохранение прогресса, конфликт версий и одноразовый сброс');
})().catch(err => { console.error(err); process.exitCode = 1; });
